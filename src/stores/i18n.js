const translations = {
  en: enTranslations,
  id: idTranslations,
};

function normalizeLocale(locale) {
  if (locale === 'bn') {
    return 'id';
  }

  return Object.prototype.hasOwnProperty.call(translations, locale)
    ? locale
    : DEFAULT_LOCALE;
}

function getInitialLocale() {
  const storedLocale = localStorage.getItem('locale');
  const locale = normalizeLocale(storedLocale || DEFAULT_LOCALE);

  if (storedLocale !== locale) {
    localStorage.setItem('locale', locale);
  }

  return locale;
}

export const useI18nStore = defineStore('i18n', {
  state: () => ({
    locale: getInitialLocale(),
    translations,
  }),
  getters: {
    t: (state) => (key) => {
      const localeTranslations = state.translations[state.locale] || state.translations[DEFAULT_LOCALE];
      return localeTranslations[key] || state.translations.en[key] || key;
    },
  },
  actions: {
    setLocale(newLocale) {
      const locale = normalizeLocale(newLocale);
      this.locale = locale;
      localStorage.setItem('locale', locale);
    },
    toggleLocale() {
      const newLocale = this.locale === 'id' ? 'en' : 'id';
      this.setLocale(newLocale);
    },
  },
});
